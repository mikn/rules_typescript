#!/usr/bin/env bash
# wrapper_config_node_modules_test.sh — the vite wrapper must leave a writable
# node_modules directly beside the generated vite.config.mjs.
#
# Vite's config loader mkdirs "<nearest node_modules above the config>/.vite-temp"
# and only tolerates EACCES. In a Bazel action the nearest one can be the exec
# root's node_modules — a symlink into the read-only source tree — and the mkdir
# then fails the build. The wrapper plants a writable one closer, which is what
# this test pins.

set -euo pipefail

fail() { echo "FAIL: $*" >&2; exit 1; }
pass() { echo "PASS: $*"; }

RUNFILES="${TEST_SRCDIR:-}"
[[ -n "${RUNFILES}" ]] || fail "TEST_SRCDIR is unset; run this through bazel test"
if [[ -d "${RUNFILES}/_main" ]]; then
  RUNFILES="${RUNFILES}/_main"
fi

WRAPPER="${RUNFILES}/vite/tests/stub_bundler_vite_wrapper.sh"
STUB="${RUNFILES}/vite/tests/stub_runtime.sh"
[[ -f "${WRAPPER}" ]] || fail "missing runfile: ${WRAPPER}"
[[ -f "${STUB}" ]] || fail "missing runfile: ${STUB}"

# A fake exec root: the wrapper reads every path relative to $(pwd), so the two
# paths it has baked in (the node_modules parent it cd's to, and the runtime)
# are all that has to exist besides the config.
strip_exec_root() { sed -e 's/^[A-Z_]*="${EXEC_ROOT}\///' -e 's/"$//'; }
NM_REL="$(grep '^NM_DIR=' "${WRAPPER}" | strip_exec_root)"
RUNTIME_REL="$(grep '^RUNTIME=' "${WRAPPER}" | strip_exec_root)"
[[ -n "${NM_REL}" && -n "${RUNTIME_REL}" ]] || fail "could not read NM_DIR/RUNTIME out of ${WRAPPER}"

EXEC="${TEST_TMPDIR}/exec_root"
mkdir -p "${EXEC}/${NM_REL}" "${EXEC}/$(dirname "${RUNTIME_REL}")" "${EXEC}/out/cfg" "${EXEC}/node_modules"
cp "${STUB}" "${EXEC}/${RUNTIME_REL}"
chmod +x "${EXEC}/${RUNTIME_REL}"
: >"${EXEC}/out/cfg/vite.config.mjs"

# Stand in for the exec root's read-only source node_modules symlink.
chmod a-w "${EXEC}/node_modules"
trap 'chmod u+w "${EXEC}/node_modules" 2>/dev/null || true' EXIT
if mkdir "${EXEC}/node_modules/.vite-temp" 2>/dev/null; then
  fail "test setup: ${EXEC}/node_modules was expected to be unwritable"
fi
pass "an unwritable node_modules sits above the config directory"

(cd "${EXEC}" && "${WRAPPER}" out/cfg/vite.config.mjs out/entry.js out "") >"${TEST_TMPDIR}/wrapper.log" 2>&1 ||
  fail "wrapper exited non-zero: $(cat "${TEST_TMPDIR}/wrapper.log")"
grep -q "STUB_RUNTIME" "${TEST_TMPDIR}/wrapper.log" ||
  fail "wrapper never reached the runtime: $(cat "${TEST_TMPDIR}/wrapper.log")"
pass "wrapper ran to the vite invocation"

SHIM="${EXEC}/out/cfg/node_modules"
[[ -d "${SHIM}" ]] || fail "no node_modules beside the generated config at ${SHIM}"
pass "node_modules exists beside the generated config"

mkdir "${SHIM}/.vite-temp" || fail "${SHIM} is not writable"
pass ".vite-temp can be created in it"

# Vite takes the NEAREST node_modules walking up from the config's directory,
# so the writable one has to be the first hit.
dir="${EXEC}/out/cfg"
found=""
while [[ -n "${dir}" && "${dir}" != "/" ]]; do
  if [[ -d "${dir}/node_modules" ]]; then
    found="${dir}/node_modules"
    break
  fi
  dir="$(dirname "${dir}")"
done
[[ "${found}" == "${SHIM}" ]] || fail "nearest node_modules above the config is ${found}, not ${SHIM}"
pass "it is the nearest node_modules above the config"

echo "All assertions passed."
